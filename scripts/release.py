"""Build a release for the website, only if every test passes.

Usage:
    uv run python scripts/release.py --base-url https://toolbox.design/hiero-mcp [--live] [--site dist/site]

Steps:
1. `pytest` (and `scripts/live_check.py` with --live, which needs Hiero open).
2. `uv build --wheel`.
3. Updates the site folder, ready to upload as-is to <base-url>:

    files/hiero_mcp-<version>-py3-none-any.whl   the download
    files/SHA256SUMS                             checksums of every wheel
    simple/index.html                            package index (PEP 503), so
    simple/hiero-mcp/index.html                  `uvx --index <base-url>/simple/ hiero-mcp@latest` finds new versions
    LICENSE.txt
    download.html                                HTML snippet for the download page

Earlier wheels already in the site folder are kept and stay listed in the index.
"""

from __future__ import annotations

import argparse
import hashlib
import html
import shutil
import subprocess
import sys
import tempfile
import tomllib
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
PACKAGE = "hiero-mcp"


def run(cmd: list[str]) -> None:
    print("$", " ".join(cmd), flush=True)
    if subprocess.run(cmd, cwd=REPO).returncode != 0:
        sys.exit(f"release aborted: {' '.join(cmd)} failed")


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def write_index(site: Path) -> list[Path]:
    wheels = sorted((site / "files").glob("hiero_mcp-*.whl"))
    links = "\n".join(f'    <a href="../../files/{w.name}#sha256={sha256(w)}">{w.name}</a><br>' for w in wheels)
    (site / "simple" / PACKAGE).mkdir(parents=True, exist_ok=True)
    (site / "simple" / PACKAGE / "index.html").write_text(
        f"<!DOCTYPE html>\n<html><head><title>Links for {PACKAGE}</title></head>\n<body>\n{links}\n</body></html>\n",
        encoding="utf-8",
    )
    (site / "simple" / "index.html").write_text(
        f'<!DOCTYPE html>\n<html><body>\n    <a href="{PACKAGE}/">{PACKAGE}</a>\n</body></html>\n',
        encoding="utf-8",
    )
    (site / "files" / "SHA256SUMS").write_text("".join(f"{sha256(w)}  {w.name}\n" for w in wheels), encoding="utf-8")
    return wheels


def download_snippet(base_url: str, wheel: Path, version: str) -> str:
    url = f"{base_url}/files/{wheel.name}"
    index = f"{base_url}/simple/"
    e = html.escape
    return f"""<!-- hiero-mcp {e(version)} download block. Generated by scripts/release.py -->
<section class="hiero-mcp-download">
  <h2>hiero-mcp {e(version)}</h2>
  <p>MCP server for Foundry Hiero / Nuke Studio 17. Lets Claude, ChatGPT/Codex, Gemini and other MCP agents work with your Hiero projects.</p>

  <p><a class="button" href="{e(url)}" download>Download hiero-mcp {e(version)} (.whl)</a></p>
  <p><small>SHA-256: <code>{sha256(wheel)}</code> &middot; Free to use, including commercially &middot;
     By downloading you accept the <a href="{e(base_url)}/LICENSE.txt">license</a>.</small></p>

  <h3>Requirements</h3>
  <ul>
    <li>Hiero, Hiero Player or Nuke Studio 17.x (tested on macOS)</li>
    <li><a href="https://docs.astral.sh/uv/getting-started/installation/">uv</a> (one-line installer)</li>
  </ul>

  <h3>1. Install the Hiero plugin</h3>
  <pre><code>uvx --index {e(index)} {PACKAGE}@latest install-plugin</code></pre>
  <p>Restart Hiero, then check the connection:</p>
  <pre><code>uvx --index {e(index)} {PACKAGE}@latest status</code></pre>

  <h3>2. Add it to your agent</h3>
  <p><strong>Claude Code</strong></p>
  <pre><code>claude mcp add hiero -- uvx --index {e(index)} {PACKAGE}@latest</code></pre>
  <p><strong>Claude Desktop</strong> (<code>claude_desktop_config.json</code>) and <strong>Gemini CLI</strong> (<code>~/.gemini/settings.json</code>)</p>
  <pre><code>{{
  "mcpServers": {{
    "hiero": {{
      "command": "uvx",
      "args": ["--index", "{e(index)}", "{PACKAGE}@latest"]
    }}
  }}
}}</code></pre>
  <p><strong>OpenAI Codex CLI</strong> (<code>~/.codex/config.toml</code>)</p>
  <pre><code>[mcp_servers.hiero]
command = "uvx"
args = ["--index", "{e(index)}", "{PACKAGE}@latest"]</code></pre>

  <p><small>Using <code>@latest</code>, agents pick up new versions automatically when they start.
     To use the downloaded file instead, replace <code>--index &hellip; {PACKAGE}@latest</code> with
     <code>--from /path/to/{e(wheel.name)} {PACKAGE}</code>.</small></p>
</section>
"""


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--base-url", required=True, help="public URL where the site folder will be uploaded")
    parser.add_argument("--site", default="dist/site", help="site folder to create or update (default dist/site)")
    parser.add_argument("--live", action="store_true", help="also run scripts/live_check.py (Hiero must be open)")
    args = parser.parse_args()
    base_url = args.base_url.rstrip("/")
    site = (REPO / args.site).resolve()

    run(["uv", "run", "pytest", "-q"])
    if args.live:
        run(["uv", "run", "python", "scripts/live_check.py"])

    version = tomllib.loads((REPO / "pyproject.toml").read_text(encoding="utf-8"))["project"]["version"]
    with tempfile.TemporaryDirectory() as tmp:
        run(["uv", "build", "--wheel", "--out-dir", tmp])
        built = next(Path(tmp).glob("hiero_mcp-*.whl"))
        (site / "files").mkdir(parents=True, exist_ok=True)
        wheel = site / "files" / built.name
        if wheel.exists() and sha256(wheel) != sha256(built):
            sys.exit(f"release aborted: {wheel.name} already published with different contents; bump the version in pyproject.toml")
        shutil.copy2(built, wheel)

    wheels = write_index(site)
    shutil.copy2(REPO / "LICENSE", site / "LICENSE.txt")
    (site / "download.html").write_text(download_snippet(base_url, wheel, version), encoding="utf-8")

    print(f"\nRelease {version} ready in {site}")
    print(f"  wheels in index: {', '.join(w.name for w in wheels)}")
    print(f"  upload the whole folder to {base_url}/ and paste download.html into your page")


if __name__ == "__main__":
    main()
